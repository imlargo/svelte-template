#!/usr/bin/env bash
# Rebuilds the template from scratch, as if done by hand:
#   1. moves the current project to legacy/
#   2. creates app/ with sv create, the shadcn-svelte skill, shadcn-svelte init, Coral and
#      every shadcn-svelte component, all of them interactive
#   3. installs the template's own dependencies
#   4. moves the template's own code into app/, replacing what the scaffold put there
#   5. replaces the project with app/ and deletes legacy/ (git keeps the previous version)
set -euo pipefail

cd "$(dirname "$0")"

readonly LEGACY=legacy
readonly APP=app
readonly SCRIPTS=(setup.sh reset.sh init.sh)
readonly KEEP_AT_ROOT=(.git "$LEGACY" "${SCRIPTS[@]}")

readonly SKILLS=(huntabyte/shadcn-svelte)
readonly CORAL_REGISTRY=https://coral.imlargo.dev/r/coral.json
readonly UI_DIR=src/lib/components/ui
# Fails svelte-check with the current shadcn-svelte (huntabyte/shadcn-svelte#2944).
readonly UI_EXCLUDED=(native-select)

readonly DEPS=(zod @imlargo/air)
readonly DEV_DEPS=(husky lint-staged)

# Welcome page and sample code from sv create.
readonly SCAFFOLD_EXAMPLES=(
	src/lib/vitest-examples
	src/routes/demo
	src/routes/+page.svelte
	src/routes/page.svelte.e2e.ts
)

# The template's code: it replaces whatever the scaffold put at the same path.
readonly OWN=(
	src/env.ts
	src/hooks.client.ts
	src/hooks.server.ts
	src/routes
	src/lib/config
	src/lib/core
	src/lib/features
	src/lib/server
	src/lib/types
	src/lib/utils
	src/lib/components/blocks
	src/lib/components/layout
	docs
	README.md
	AGENTS.md
	.github
	.husky
	.env
	.env.example
	.env.test
)

# Folders the installers also write to: only the template's files they lack are moved.
readonly SHARED=(src/lib/hooks src/lib/assets static)

# Generated by the installers inside the folders above: the new one stays.
readonly NOT_MOVED=(src/routes/layout.css)

log() { printf '\n\033[1;34m==> %s\033[0m\n' "$*"; }

contains() {
	local needle=$1 item
	shift
	for item in "$@"; do
		[[ $item == "$needle" ]] && return 0
	done
	return 1
}

in_app() { (cd "$APP" && "$@"); }

check_clean_tree() {
	if [[ -e $APP || -e $LEGACY ]]; then
		echo "$APP/ or $LEGACY/ already exists: run ./reset.sh first." >&2
		exit 1
	fi
	if [[ -n $(git status --porcelain -- . "${SCRIPTS[@]/#/:!}") ]]; then
		echo "The working tree has changes: commit or stash them first." >&2
		exit 1
	fi
}

move_to_legacy() {
	log "Moving the current project to $LEGACY/"
	mkdir "$LEGACY"
	shopt -s dotglob nullglob
	local item
	for item in *; do
		contains "$item" "${KEEP_AT_ROOT[@]}" || mv "$item" "$LEGACY/"
	done
	shopt -u dotglob nullglob
}

create_app() {
	log "Creating $APP/ with sv create (pick pnpm: the next steps use it)"
	npx -y sv@latest create "$APP"
	rm -rf "${SCAFFOLD_EXAMPLES[@]/#/$APP/}"
}

install_skills() {
	local skill
	for skill in "${SKILLS[@]}"; do
		log "Installing the $skill skill"
		in_app pnpm dlx skills add "$skill"
	done
}

install_components() {
	log "Installing shadcn-svelte"
	in_app pnpm dlx shadcn-svelte@latest init

	# Coral before `add -a`: it installs the shadcn primitives it is built on, and
	# `add -a` then leaves every primitive on its latest version.
	log "Installing Coral"
	in_app pnpm dlx shadcn-svelte@latest add "$CORAL_REGISTRY"

	log "Adding every shadcn-svelte component"
	in_app pnpm dlx shadcn-svelte@latest add -a -y -o
	rm -rf "${UI_EXCLUDED[@]/#/$APP/$UI_DIR/}"
}

install_deps() {
	log "Installing the template's dependencies"
	in_app pnpm add "${DEPS[@]}"
	in_app pnpm add -D "${DEV_DEPS[@]}"
}

# Moves every file under legacy/$1 into app/. `replace` overwrites what is there, `keep`
# leaves the installed file and the template's in legacy/.
move() {
	local path=$1 policy=$2 file rel
	[[ -e $LEGACY/$path ]] || return 0
	while IFS= read -r -d '' file; do
		rel=${file#"$LEGACY"/}
		contains "$rel" "${NOT_MOVED[@]}" && continue
		[[ $policy == keep && -e $APP/$rel ]] && continue
		mkdir -p "$APP/$(dirname "$rel")"
		mv -f "$file" "$APP/$rel"
	done < <(find "$LEGACY/$path" \( -type f -o -type l \) -print0)
}

move_own_code() {
	log "Moving the template's code"
	local path
	for path in "${OWN[@]}"; do
		move "$path" replace
	done
	for path in "${SHARED[@]}"; do
		move "$path" keep
	done
}

# The pre-commit hook runs lint-staged, whose config lives in package.json.
move_lint_staged_config() {
	node -e '
		const fs = require("fs");
		const [from, to] = process.argv.slice(1);
		const app = JSON.parse(fs.readFileSync(to, "utf8"));
		app["lint-staged"] = JSON.parse(fs.readFileSync(from, "utf8"))["lint-staged"];
		fs.writeFileSync(to, JSON.stringify(app, null, "\t") + "\n");
	' "$LEGACY/package.json" "$APP/package.json"
}

# node_modules is reinstalled at the root: pnpm's bin shims carry absolute paths.
promote_app() {
	log "Replacing the project with $APP/"
	rm -rf "$LEGACY" "$APP/node_modules" "$APP/.svelte-kit"
	shopt -s dotglob nullglob
	mv "$APP"/* .
	shopt -u dotglob nullglob
	rmdir "$APP"
	pnpm install
	pnpm run --if-present gen
}

check_clean_tree
move_to_legacy
create_app
install_skills
install_components
install_deps
move_own_code
move_lint_staged_config
promote_app

log "Done: review the changes with git status and git diff"
